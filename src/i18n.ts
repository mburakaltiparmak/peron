export function errorText(t: Dict, e: AppError): string {
  switch (e.kind) {
    case "accessDenied":
      return t.errAccessDenied;
    case "notFound":
      return t.errNotFound;
    case "protected":
      return t.errProtected(e.detail ?? "");
    case "changed":
      return t.errChanged;
    case "rateLimited":
      return t.errRateLimited(e.detail ?? "60");
    case "remote": {
      const base = t.remoteErrors[e.code ?? "other"] ?? t.remoteErrors.other;
      return e.detail ? `${base} (${e.detail})` : base;
    }
    default:
      return e.detail?.includes("UAC") ? t.errUac : e.detail ?? e.message;
  }
}
